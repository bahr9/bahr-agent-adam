def run_test(name, fn):
    try:
        fn()
        print("OK  " + name)
        return True
    except AssertionError as e:
        print("FAIL " + name + ": " + str(e))
        return False
    except Exception as e:
        print("FAIL " + name + ": خطأ غير متوقع -- " + type(e).__name__ + ": " + str(e))
        return False


def main():
    from services import claude_service as cs

    SRC = open(cs.__file__, encoding="utf-8").read()
    PROMPT = SRC.split('"name": "', 1)[0]

    def أسعار_الموردين_مش_عن_طريق_البحث():
        """web_search بترجع نص من غير وحدة قياس -- والوحدة الغلط بتبوّظ المقايسة."""
        assert "check_supplier_price" in PROMPT, "الأداة مش مذكورة في قاعدة الموردين"
        assert "متستخدمش web_search للأسعار" in PROMPT, \
            "مفيش منع صريح لاستخدام web_search في الأسعار"
        assert "site:mahgoub.com" not in PROMPT, \
            "قاعدة البحث القديمة لسه موجودة -- هتنافس الأداة الجديدة"

    def بيانات_المشاريع_ليها_مخزن_واحد():
        """التعارض ده كان بيبعثر بيانات المشاريع على مخزنين."""
        import re
        # كل سطر بيتكلم عن حقائق مشاريع العملاء لازم يوجّه لـsave_project_fact
        for line in PROMPT.splitlines():
            if "حقائق مشاريع العملاء" in line:
                assert "save_project_fact" in line, "بيوجّه لمخزن تاني: " + line[:120]
                assert "مش save_memory_note" in line, \
                    "مفيش استبعاد صريح للمخزن التاني: " + line[:120]
                break
        else:
            raise AssertionError("سطر حقائق مشاريع العملاء اختفى")

    def فيه_منع_للتسجيل_المزدوج():
        assert "ومتسجلش الاتنين لنفس المعلومة" in PROMPT, \
            "مفيش منع لتسجيل نفس المعلومة في المخزنين"

    def الحفظ_التلقائي_بيستثني_الشغل_التقني():
        """146 من 183 ملاحظة كانت عن بناء آدم -- دي القاعدة اللي ولّدتهم."""
        assert "متسجّلش الشغل التقني على نفسك" in PROMPT, \
            "مفيش استثناء للشغل التقني في قاعدة الحفظ التلقائي"
        assert "مفيش save_memory_note" in PROMPT, "الاستثناء مش قاطع"

    def الحفظ_التلقائي_لسه_شغال_لشغل_أحمد():
        """الاستثناء مايلغيش القاعدة -- الحفظ التلقائي لشغله هو المطلوب."""
        assert "اتفقت مع العميل على سعر 50 ألف" in PROMPT, \
            "أمثلة شغل أحمد اتشالت مع الاستثناء"

    def خط_الأسعار_الأحمر_لسه_موجود():
        """أهم قاعدة أمانة في الملف -- ممنوع تتشال في تنضيف تكلفة."""
        assert "قبل ما تقول أي سعر" in PROMPT and "get_prices الأول" in PROMPT
        assert "ممنوع تخترع رقم" in PROMPT
        assert "ممنوع منعًا باتًا" in PROMPT, "منع تسجيل سعر المورد اتشال"

    def قواعد_المقايسة_والبلانات_سليمة():
        for must in ("estimate_project_cost", "ممنوع تحسب بإيدك",
                     "save_prices_bulk", "get_open_threads"):
            assert must in PROMPT, "اتشال من البرومبت: " + must

    results = [
        run_test("أسعار الموردين مش عن طريق البحث", أسعار_الموردين_مش_عن_طريق_البحث),
        run_test("بيانات المشاريع ليها مخزن واحد", بيانات_المشاريع_ليها_مخزن_واحد),
        run_test("فيه منع للتسجيل المزدوج", فيه_منع_للتسجيل_المزدوج),
        run_test("الحفظ التلقائي بيستثني التقني", الحفظ_التلقائي_بيستثني_الشغل_التقني),
        run_test("الحفظ التلقائي لسه شغال لشغله", الحفظ_التلقائي_لسه_شغال_لشغل_أحمد),
        run_test("خط الأسعار الأحمر موجود", خط_الأسعار_الأحمر_لسه_موجود),
        run_test("قواعد المقايسة والبلانات سليمة", قواعد_المقايسة_والبلانات_سليمة),
    ]

    print()
    passed = sum(1 for r in results if r)
    print(str(passed) + "/" + str(len(results)) + " اختبار عدّى")
    return 0 if passed == len(results) else 1


if __name__ == "__main__":
    raise SystemExit(main())
