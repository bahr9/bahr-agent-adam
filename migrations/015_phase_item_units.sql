-- ============================================================
-- 015 — توسيع وحدات بنود المقايسة
-- ============================================================
-- التاريخ: 2026-08-10
--
-- 003 حطّ القيد على أربع وحدات: مقطوعية · م.ط · م² · م³.
-- القايمة دي كانت مأخوذة من الـselect في فرونت BAHR OS، مش من الداتا.
--
-- أول نقل حقيقي (Rock Eden، 95 بند مقايسة) أثبت إن الأربعة مش كافيين:
--
--     عدد      16 بند   -- عدّ قطع. «قواطيع ستانليس 9.5 عدد» = تسع قطع
--                          ونص فعلاً، وتحويلها لمقطوعية بيزوّر الرقم
--                          عشان يعدّي من القيد.
--     فاتورة    1 بند   -- «خامات (مرفق فواتير)» -- بيتحاسب بالفاتورة.
--
-- (وفيه تسع بنود تانية كانت `م2` و`مق` -- دول ترميز مش معنى، اتطبّعوا
--  في سكربت النقل لـ`م²` و`مقطوعية` وكل واحد اتطبع بالاسم.)
--
-- القاعدة اللي القرار اتاخد عليها: **القيد يوصف الداتا، مش يلويها.**
-- لما وحدة حقيقية في مقايسة حقيقية ترفضها السكيما، السكيما هي اللي
-- ناقصة.
--
-- ⚠️ حصل فخ تاني كان هيبان بعد النقل: الـselect في الفرونت كان أربع
--    خيارات، فبند وحدته «عدد» كان بيقع على أول خيار («مقطوعية») ومجرد
--    فتح المقايسة وحفظها كان بيحوّل الستاشر بند في صمت -- نفس التزوير
--    اللي القيد ده اتوسّع عشان يمنعه. الفرونت اتظبط لستة خيارات واتنشر
--    قبل النقل.
--
-- جدول الحصر (`project_quantity_items`) **مقصود إن قيده مايتوسعش**:
-- بنوده الـ11 وحداتها سليمة، والأبعاد الخام هناك بيتحسب منها المقدار
-- حسب الوحدة -- فوحدة مش معروفة معناها حساب مش معروف.
-- ============================================================

begin;

alter table public.project_phase_items
    drop constraint if exists project_phase_items_unit_valid;

alter table public.project_phase_items
    add constraint project_phase_items_unit_valid
    check (unit in ('مقطوعية', 'م.ط', 'م²', 'م³', 'عدد', 'فاتورة'));

comment on constraint project_phase_items_unit_valid on public.project_phase_items is
    'ستة وحدات من 2026-08-10. الأربعة الأصليين كانوا من قايمة الفرونت؛ '
    '«عدد» و«فاتورة» اتضافوا لما أول نقل حقيقي رفض 17 بند بيهم. '
    'قايمة الفرونت اتوسّعت لنفس الستة في نفس اليوم.';

commit;


