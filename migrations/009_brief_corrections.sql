-- 009: تصحيحات أحمد على إجابات العميل
--
-- المشكلة: العميل بيقول "شقة" وتطلع دوبلكس في المعاينة. أحمد محتاج يصحّح،
-- **بس تعديل إجابة العميل ممنوع** -- الإجابات دليل، والقراءة اللي آدم بيطلعها
-- متبنية عليها، ودستور آدم بيقول الحقائق بتتنقل حرفيًا (CONSTITUTION.md §0).
--
-- الحل: طبقة فوق مش تعديل تحت.
--   answers      -- كلام العميل، **ثابت للأبد**
--   corrections  -- تصحيح أحمد فوقه، بتاريخه وسببه
--
-- الشكل:
--   {"نوع الوحدة": {"to": "دوبلكس", "at": "2026-08-10T…", "why": "اتأكدت في المعاينة"}}
--
-- عمود jsonb زي answers -- نفس النمط، صفر جداول جديدة.

alter table client_briefs add column if not exists corrections jsonb not null default '{}'::jsonb;
