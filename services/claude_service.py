            # قبل كده أي سبب مش "tool_use" كان بيترجع كإجابة نهائية -- يعني
            # بحث وِب وقف في النص، أو رد اتقطع عند حد التوكنز، أو رفض، كلهم
            # كانوا بيوصلوا لأحمد كأنهم رد كامل ومقصود.
