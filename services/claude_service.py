def _extract_json(raw_text):
    """
    يحاول يقرا JSON من رد الموديل، حتى لو فيه كلام زيادة حواليه.
    بيرجع dict أو None لو فشل تمامًا.
    """
    if not raw_text:
        return None
    
    cleaned = raw_text.replace("```json", "").replace("```", "").strip()
    
    # محاولة مباشرة
    try:
        return json.loads(cleaned)
    except Exception:
        pass
    
    # محاولة تانية: لقط أول { ... } في النص (لو فيه كلام زيادة قبله أو بعده)
    match = re.search(r"\{.*\}", cleaned, re.DOTALL)
    if match:
        try:
            return json.loads(match.group(0))
        except Exception:
            pass
    
    return None

def _tracked_create(**kwargs):
    """غلاف حول messages.create بيسجّل الاستهلاك -- الإجابة الحقيقية لسؤال
    "الرصيد بيروح فين؟" (2026-08-06، بعد ما الرصيد خلص فجأة).

    بيسجل لكل نداء: الدالة المنادية، الموديل، توكنز الدخل/الخرج/الكاش --
    في Supabase (جدول api_usage) بأفضل جهد، وفي اللوج دايمًا. لو الجدول
    لسه متعملش بيتخطى بصمت -- التتبع ميعطلش الشغل أبدًا.
    """
    import inspect
    caller = "unknown"
    try:
        caller = inspect.stack()[1].function
    except Exception:
        pass

    # كاش بعمر ساعة (توفير 2026-08-06): الافتراضي 5 دقايق، ورسايل أحمد
    # الطبيعية أبعد من كده -- فكل رسالة كانت بتدفع إعادة كتابة البادئة
    # الثابتة كاملة (~14.5K توكن × 1.25). بعمر ساعة: كتابة واحدة (×2)
    # كل ساعة نشاط، والباقي قراءات بـ 0.1× -- وفر ~3-4x على أكبر بند تكلفة.
    kwargs.setdefault("extra_headers", {}).setdefault(
        "anthropic-beta", "extended-cache-ttl-2025-04-11")
    response = claude_client.messages.create(**kwargs)

    try:
        u = response.usage
        cache_read = getattr(u, "cache_read_input_tokens", 0) or 0
        cache_write = getattr(u, "cache_creation_input_tokens", 0) or 0
        logger.info(
            f"💸 [{caller}] {kwargs.get('model','?')}: in={u.input_tokens} out={u.output_tokens} "
            f"cache_r={cache_read} cache_w={cache_write}"
        )
        from services import supabase_store
        client = supabase_store._client()
        if client is not None:
            try:
                client.table("api_usage").insert({
                    "caller": caller,
                    "model": kwargs.get("model", "?"),
                    "input_tokens": u.input_tokens,
                    "output_tokens": u.output_tokens,
                    "cache_read_tokens": cache_read,
                    "cache_write_tokens": cache_write,
                }).execute()
            except Exception:
                pass    # الجدول لسه متعملش -- التتبع اختياري
    except Exception:
        pass

    return response


